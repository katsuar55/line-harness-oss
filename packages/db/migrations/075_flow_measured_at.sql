-- 075: 実測の「受信時刻」を持つ (C2 — リマインド送信を実測に限定する述語の土台)
--
-- 背景: C2 でリマインド送信対象を estimate_source='flow' (Flow 実測) に限定する。
-- ただし「実測である」ことと「実測が新しい」ことは別 — アンカー日付からは
-- 受信の新旧を判定できない (トリガー1 は同じ日付を再送してくるため、
-- 前サイクルの古い実測と今サイクルの実測がアンカー上は区別できないケースがある)。
-- 「お届け日変更 + 7日前通知」の両 Flow が失われた契約では、古い実測日が
-- そのまま窓に入り誤送信になる。受信時刻そのものを持てば
-- 「今サイクルの実測が届いた契約にだけ送る」を述語で表現できる。
--
-- 書込は recordFlowMeasurement() のみ (= estimate_source='flow' を書く唯一の経路)。
-- 実注文で derived に戻る時・停止/解約でアンカーを消費する時に一緒にクリアする。
--
-- ⚠️ 意図的に既存行の初期化 UPDATE を **しない**: 既存の flow 行の受信時刻は
-- 記録されていない = 鮮度不明。鮮度不明を「新しい」とみなすのは C2 の趣旨
-- (誤送信は回復不能・無送信は回復可能) に反する。NULL のままなら送信対象外で、
-- 次のトリガー発火 (7日前通知/スキップ/お届け日変更) で時刻付き実測に置き換わる。
ALTER TABLE subscription_contracts ADD COLUMN flow_measured_at TEXT;
